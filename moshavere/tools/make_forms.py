BUILDERS = [doc_index, doc_intake, doc_weekly, doc_daily, doc_exam,
            doc_screen, doc_service, doc_parents, doc_guide_counselor,
            doc_guide_teacher]


def main():
    ap = argparse.ArgumentParser(description="ساخت بستهٔ PDF مشاورهٔ کنکور")
    ap.add_argument("--out", default="../forms", help="پوشهٔ خروجی")
    a = ap.parse_args()

    fd = register_fonts()
    print(f"فونت: {fd}", file=sys.stderr)

    out = Path(a.out).expanduser().resolve()
    out.mkdir(parents=True, exist_ok=True)

    made = []
    for fn in BUILDERS:
        p = fn(out)
        size = Path(p).stat().st_size
        made.append((Path(p).name, size))
        print(f"  ✓ {Path(p).name}  ({size/1024:.0f} KB)", file=sys.stderr)

    total = sum(s for _, s in made)
    print(f"\n{len(made)} سند ساخته شد — مجموع {total/1024:.0f} KB",
          file=sys.stderr)
    print(f"پوشه: {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
