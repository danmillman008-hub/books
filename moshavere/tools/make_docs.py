def d_cards(out):
    path = out / "09-cart-vizit.pdf"
    n = len(COUNSELORS)

    def front(c, x, y, w, h):
        c.setFillColor(colors.white)
        c.rect(x, y, w, h, stroke=0, fill=1)
        c.setFillColor(ACCENT)
        c.rect(x, y + h - 5, w, 5, stroke=0, fill=1)
        # هر کارت به یک مشاور اختصاص دارد؛ به‌نوبت
        idx = front.i % n
        front.i += 1
        name, role = COUNSELORS[idx]
        c.setFont("FA-B", 11.5)
        c.setFillColor(INK)
        c.drawRightString(x + w - 14, y + h - 32, shape(name))
        c.setFont("FA", 7.8)
        c.setFillColor(MUTED)
        c.drawRightString(x + w - 14, y + h - 45, shape(role))
        c.setStrokeColor(RULE)
        c.setLineWidth(0.5)
        c.line(x + 14, y + h - 55, x + w - 14, y + h - 55)
        c.setFont("FA-B", 9.5)
        c.setFillColor(ACCENT)
        c.drawRightString(x + w - 14, y + h - 72, shape(INST))
        c.setFont("FA", 6.6)
        c.setFillColor(MUTED)
        c.drawRightString(x + w - 14, y + h - 83, shape(TAGLINE))
        c.setFont("FA", 7)
        c.setFillColor(INK)
        yy = y + 32
        for line in (PHONE, SITE, INSTAGRAM):
            c.drawRightString(x + w - 14, yy, shape(line))
            yy -= 10
    front.i = 0

    def back(c, x, y, w, h):
        c.setFillColor(ACCENT)
        c.rect(x, y, w, h, stroke=0, fill=1)
        c.setFont("FA-B", 13)
        c.setFillColor(colors.white)
        c.drawCentredString(x + w / 2, y + h / 2 + 6, shape(INST_SHORT))
        c.setFont("FA", 7.4)
        c.drawCentredString(x + w / 2, y + h / 2 - 10, shape(TAGLINE))

    return business_cards(path, front, back)


