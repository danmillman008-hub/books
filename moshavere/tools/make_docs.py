BUILDERS = [d_interview, d_weekly, d_daily, d_answersheet, d_exam,
            d_progress, d_contract, d_catalog, d_cards, d_playbook]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="../../pdf")
    a = ap.parse_args()
    print(f"فونت: {register_fonts()}", file=sys.stderr)
    out = Path(a.out).expanduser().resolve()
    out.mkdir(parents=True, exist_ok=True)
    tot = 0
    for fn in BUILDERS:
        p = Path(fn(out))
        s = p.stat().st_size
        tot += s
        print(f"  ✓ {p.name}  ({s/1024:.0f} KB)", file=sys.stderr)
    print(f"\n{len(BUILDERS)} سند — مجموع {tot/1024:.0f} KB\n{out}",
          file=sys.stderr)


if __name__ == "__main__":
    main()
